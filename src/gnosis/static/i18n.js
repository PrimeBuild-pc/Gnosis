const LANGUAGES = [
  ['en', 'English'],
  ['it', 'Italiano'],
];

let currentLanguage =
  localStorage.getItem('gnosis-lang') ||
  (navigator.language || 'en').slice(0, 2).toLowerCase();
if (!I18N[currentLanguage]) currentLanguage = 'en';

const t = (key, vars) => {
  let text = I18N[currentLanguage][key] ?? I18N.en[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value);
  return text;
};

const setLanguage = language => {
  currentLanguage = I18N[language] ? language : 'en';
  localStorage.setItem('gnosis-lang', currentLanguage);
  document.documentElement.lang = currentLanguage;
  applyTranslations();
};

// Traduce ogni nodo marcato nell'HTML. Gli attributi coprono testo, placeholder e title,
// che sono gli unici punti in cui compaiono stringhe statiche.
const applyTranslations = () => {
  document.querySelectorAll('[data-i18n]').forEach(node => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(node => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(node => {
    node.title = t(node.dataset.i18nTitle);
  });
  document.dispatchEvent(new CustomEvent('gnosis:language'));
};
