const LANGUAGES = [
  ['en', 'English'],
  ['it', 'Italiano'],
  ['es', 'Español'],
  ['ru', 'Русский'],
  ['zh', '中文'],
];

const supportedLanguage = value => {
  const code = typeof value === 'string' ? value.toLowerCase().split(/[-_]/)[0] : '';
  return Object.hasOwn(I18N, code) ? code : null;
};

const readPreference = key => {
  try { return localStorage.getItem(key); } catch { return null; }
};
const writePreference = (key, value) => {
  try { localStorage.setItem(key, value); } catch { /* Keep working when storage is blocked. */ }
};
const savedLanguage = readPreference('gnosis-lang');
const browserLanguages = navigator.languages?.length ? navigator.languages : [navigator.language];
let currentLanguage = supportedLanguage(savedLanguage)
  || browserLanguages.map(supportedLanguage).find(Boolean) || 'en';
document.documentElement.lang = currentLanguage;

const t = (key, vars = {}) => {
  const translated = Object.hasOwn(I18N[currentLanguage], key) ? I18N[currentLanguage][key] : undefined;
  const fallback = Object.hasOwn(I18N.en, key) ? I18N.en[key] : key;
  const text = translated ?? fallback;
  // One pass keeps user-supplied braces and replacement characters literal.
  return text.replace(/\{(\w+)\}/g, (placeholder, name) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : placeholder);
};

const formatDate = (value, dateOnly = false) => {
  if (!value) return t('date.unknown');
  // Calendar dates have no timezone; avoid shifting a digest to the previous day.
  const date = new Date(dateOnly && /^\d{4}-\d{2}-\d{2}$/.test(value) ? `${value}T00:00:00` : value);
  if (Number.isNaN(date.getTime())) return t('date.unknown');
  return dateOnly ? date.toLocaleDateString(currentLanguage) : date.toLocaleString(currentLanguage);
};

const setLanguage = language => {
  currentLanguage = supportedLanguage(language) || 'en';
  writePreference('gnosis-lang', currentLanguage);
  document.documentElement.lang = currentLanguage;
  applyTranslations();
};

// Update copy in place: switching language must not discard drafts, answers or focus.
const applyTranslations = () => {
  document.querySelectorAll('[data-i18n]').forEach(node => {
    node.textContent = t(node.dataset.i18n);
  });
  for (const [attribute, property] of [['placeholder', 'placeholder'], ['title', 'title'], ['aria-label', null]]) {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(node => {
      const value = t(node.getAttribute(`data-i18n-${attribute}`));
      if (property) node[property] = value;
      else node.setAttribute(attribute, value);
    });
  }
  document.querySelectorAll('[data-i18n-live]').forEach(node => node.localize());
  document.dispatchEvent(new CustomEvent('gnosis:language'));
};
